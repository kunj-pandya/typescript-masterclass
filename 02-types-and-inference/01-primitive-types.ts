// -> number : Represents integers, floats, decimals.
let age: number = 24;

//Note : JavaScript does not have a special runtime value for integers, so there’s no equivalent to int or float - everything is simply number

// -> boolean : Represents true/false values.
let isStudent: boolean = true;

// -> null: Represents absence of value.
let data: null = null;

// -> undefined : Represents a variable that is declared but not assigned.
